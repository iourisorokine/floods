import type { Level } from "./types.ts";

// ============================================================================
//  FLOODS — levels
//
//  heights: one string per row, one digit per square (0..6)
//           0 = water (always), 1 dark brown, 2 light brown,
//           3 light grass, 4..6 darker grass
//  objects: same size grid
//           .  nothing
//           H  house   (must be protected, tractor cannot drive on it)
//           R  road    (must be protected, tractor can drive on it)
//           Y  tree    (not scored, blocks the tractor, cannot be built on)
//           B  building (worth 3, keeps water out, lost if water touches it)
//           S  shop    (worth 2)
//           F  field   (worth 0.5, tractor drives slowly on it)
//           P  pine    (blocks the tractor, can be cut down with SPACE)
//           X  rock    (blocks the tractor, holds water 2 levels higher)
//           O  boulder (like a rock, but the tractor can push it)
//           C  cracked dike (breaks when the water pushes on it, repair with a tube)
//           T  tractor start position
//
//  Per-level values (fall back to CONFIG defaults when missing):
//    id              short label shown in the menu ('0a', '1', ...)
//    timer           seconds before the water rises (0 = no limit, press F)
//    floodAmplitude  how many levels the water rises
//    tubeBudget      number of protection tubes available
//    riseInterval    seconds between each +1 rise of the water
//    stars           [1 star, 2 stars, 3 stars] fraction of objects saved
//    startDir        'up' | 'down' | 'left' | 'right'
//    intro           text shown before the level starts and in the side panel
//    explainer       short explanation of a new mechanic, shown before the level
//    waves           [{ rise, pause }] several waves instead of floodAmplitude
//    night           true = only the area around the tractor is visible
//    branchFrom      side level: optional branch after this level id
//    tutorial        [{ text, until, mark }] step-by-step hints
//                    until: 'moved' | 'tubes>=N' | 'tubes@x,y>=N' | 'at x,y'
//                           | 'height>=N' | 'flood'
//                    mark:  [[x, y], ...] squares to highlight
//
//  Tip: run `npm run check-levels` (add `-- -v` for maps) to see what floods,
//  the minimum number of tubes needed and a bot's estimated solve time.
// ============================================================================

